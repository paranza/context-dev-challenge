const CAPTURED_AT = "2026-11-14T18:30:00.000Z";
const SAMPLE_BASE = "https://example.com/tender-fit-radar-demo";

function sampleSource(label: string, path: string, detail?: string): EvidenceSource {
  return {
    label: `${label} · sample`,
    url: `${SAMPLE_BASE}/${path}`,
    detail,
    capturedAt: CAPTURED_AT,
  };
}

function requirement(
  id: string,
  criterion: string,
  category: string,
  mandatory: boolean,
  status: TenderRequirement["status"],
  tenderEvidence: string,
  supplierEvidence: string,
  tenderPath: string,
  supplierPath: string | null,
): TenderRequirement {
  return {
    id,
    criterion,
    category,
    mandatory,
    status,
    tenderEvidence,
    supplierEvidence,
    tenderSource: sampleSource("Tender requirement", tenderPath, tenderEvidence),
    supplierSource: supplierPath
      ? sampleSource("Supplier evidence", `supplier/${supplierPath}`, supplierEvidence)
      : null,
  };
}

function tender(
  data: Omit<TenderResult, "url" | "sources" | "updatedAt">,
): TenderResult {
  return {
    ...data,
    url: `${SAMPLE_BASE}/tenders/${data.id}/notice`,
    sources: [
      sampleSource("Tender notice", `tenders/${data.id}/notice`),
      sampleSource("Technical specification", `tenders/${data.id}/specification`),
      sampleSource("Qualification requirements", `tenders/${data.id}/qualifications`),
      sampleSource("Buyer clarification", `tenders/${data.id}/clarification`),
    ],
    updatedAt: CAPTURED_AT,
  };
}

